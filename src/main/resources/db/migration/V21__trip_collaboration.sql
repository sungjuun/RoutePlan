CREATE TABLE trip_members (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id BIGINT NOT NULL REFERENCES trips(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    role VARCHAR(20) NOT NULL CHECK (role IN ('OWNER', 'EDITOR', 'VIEWER')),
    invited_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    joined_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uk_trip_members_trip_user UNIQUE (trip_id, user_id)
);

CREATE INDEX ix_trip_members_user ON trip_members(user_id, joined_at DESC);

INSERT INTO trip_members(trip_id, user_id, role, invited_by, joined_at)
SELECT trip.id, trip.user_id, 'OWNER', trip.user_id, trip.created_at
FROM trips trip
ON CONFLICT (trip_id, user_id) DO NOTHING;

CREATE TABLE trip_place_votes (
    trip_id BIGINT NOT NULL,
    place_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    value VARCHAR(10) NOT NULL CHECK (value IN ('YES', 'NO')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (trip_id, place_id, user_id),
    CONSTRAINT fk_trip_place_votes_place FOREIGN KEY (trip_id, place_id)
        REFERENCES trip_places(trip_id, place_id) ON DELETE CASCADE,
    CONSTRAINT fk_trip_place_votes_member FOREIGN KEY (trip_id, user_id)
        REFERENCES trip_members(trip_id, user_id) ON DELETE CASCADE
);

CREATE INDEX ix_trip_place_votes_place ON trip_place_votes(trip_id, place_id);

