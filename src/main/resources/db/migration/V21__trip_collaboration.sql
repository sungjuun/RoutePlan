CREATE TABLE trip_expense_participants (
    expense_id BIGINT NOT NULL REFERENCES trip_expenses(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    nickname_snapshot VARCHAR(50) NOT NULL,
    share_minor BIGINT NOT NULL CHECK (share_minor BETWEEN 0 AND 1000000000000),
    PRIMARY KEY (expense_id, user_id)
);

INSERT INTO trip_expense_participants(expense_id, user_id, nickname_snapshot, share_minor)
SELECT expense.id, trip.user_id, app_user.nickname, expense.amount_minor
FROM trip_expenses expense
JOIN trips trip ON trip.id = expense.trip_id
JOIN users app_user ON app_user.id = trip.user_id
ON CONFLICT (expense_id, user_id) DO NOTHING;

CREATE INDEX ix_trip_expense_participants_user ON trip_expense_participants(user_id, expense_id);
